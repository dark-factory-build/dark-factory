#!/usr/bin/env node
// Simulated UI proof only; the isolated daemon tests prove persistence and delivery.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
const origin = process.env.DARK_FACTORY_FIXTURE_URL || 'http://127.0.0.1:5197';
assert.equal(new URL(origin).hostname, '127.0.0.1');
const require = createRequire(process.env.DARK_FACTORY_PLAYWRIGHT_PACKAGE || join(homedir(), 'dark-factory-site', 'package.json'));
const { chromium, expect } = require('@playwright/test');
const output = resolve(process.env.DARK_FACTORY_VISUAL_OUTPUT || 'output/playwright/knowledge');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
const page = await context.newPage(), errors = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
const check = name => { checks.push(name); console.log(`PASS ${name}`); };
const click = name => page.getByRole('button', { name, exact: true }).click();
const selected = () => page.getByRole('region', { name: 'Selected library revision' });
const editor = () => page.getByRole('form', { name: 'Knowledge editor' });
const save = async (title, body) => { await editor().getByRole('textbox', { name: 'Title', exact: true }).fill(title); await editor().getByRole('textbox', { name: 'Body', exact: true }).fill(body); await editor().getByRole('button', { name: 'Save revision', exact: true }).click(); await expect(editor()).toHaveCount(0); };
try {
 await page.goto(`${origin}/?fixture=inhabited`, { waitUntil: 'networkidle' });
 await page.getByRole('searchbox', { name: 'Find source', exact: true }).fill('internal/kernel');
 await page.locator('.dfFactoryEntityTools__results').getByRole('button', { name: 'internal/kernel', exact: true }).click();
 await click('Discuss this source');
 await click('New discussion');
 await editor().getByRole('textbox', { name: 'Supporting evidence (one reference per line)' }).fill('internal/kernel/peer_question.go');
 await save('Exact-run delivery finding', 'Reviewer finding: stale replies must not reopen terminal tasks.');
 await expect(selected()).toContainText('unresolved discussion');
 const entityButton = selected().getByRole('button', { name: /^Source:/ });
 await expect(entityButton).toHaveCount(1);
 const entity = (await entityButton.textContent()).slice('Source: '.length);
 check('source-specific board posting retains stable entity');
 await click('Reply');
 await save('Operator confirms reservation', 'Keep the reply bound to the admitted run and retain the delivery receipt.');
 await selected().getByRole('button', { name: /^Original discussion:/ }).click();
 await click('Read body'); await click('Read replies');
 await expect(selected()).toContainText('Operator confirms reservation');
 await click('Pin discussion'); await click('Resolve discussion');
 await expect(selected()).toContainText('resolved discussion');
 await page.screenshot({ path: join(output, '01-resolved-thread.png') });
 check('reply, exact root revision, pin and resolution');
 await click('Retain conclusion');
 await editor().getByRole('combobox', { name: 'Status', exact: true }).selectOption('current');
 await save('Preserve exact-run reply authority', 'Reserve delivery for the admitted run. Never reopen completed work to deliver a note.');
 await expect(selected()).toContainText('Knowledge status: current');
 await click('Revise document');
 await save('Preserve exact-run reply authority', 'Reserve delivery for the admitted run and reconcile its receipt before any retry.');
 await expect(selected()).toContainText('Revision 2');
 await selected().getByRole('combobox', { name: 'Attach to queued task' }).selectOption({ label: 'Tighten the queue ordering' });
 await click('Attach revision'); await expect(page.getByRole('status').filter({ hasText: 'Attached to the task.' })).toBeVisible();
 await click('Retrieval records');
 await page.screenshot({ path: join(output, '02-retained-revision.png') });
 check('retain, revise, attach and inspect retrieval records without inventing worker reads');
 await selected().getByRole('button', { name: `Source: ${entity}`, exact: true }).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('region', { name: 'Source notices' })).toBeVisible();
 await page.getByRole('combobox', { name: 'Topology detail', exact: true }).selectOption('coarse');
 await expect(page.getByRole('region', { name: 'Source notices' })).toBeVisible();
 await click('Board'); await page.getByRole('checkbox', { name: 'Include resolved discussions' }).check();
 await page.getByRole('searchbox', { name: 'Search knowledge' }).fill('Exact-run'); await click('Search');
 await page.getByRole('button', { name: /^Exact-run delivery finding · discussion/ }).click();
 await expect(selected()).toContainText('resolved discussion');
 await click('CLOSE'); await click('Library');
 await page.getByText('Instructions & outcomes', { exact: true }).click();
 await page.getByRole('searchbox', { name: 'Search knowledge' }).fill('Preserve exact-run'); await click('Search');
 await page.getByRole('button', { name: /^Preserve exact-run reply authority · lesson · r2/ }).click();
 await click('Read body'); await expect(selected()).toContainText('reconcile its receipt before any retry');
 await page.screenshot({ path: join(output, '03-search-and-source.png') });
 check('source links survive detail changes; board and shelves search same records');
 assert.deepEqual(errors, []);
 await writeFile(join(output, 'report.json'), JSON.stringify({ fixture: true, modelBehaviorTested: false, checks, errors }, null, 2));
} finally { await browser.close(); }
